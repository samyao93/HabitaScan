-- Exporte la structure complète du schéma public (tables, contraintes, index, RLS, politiques,
-- fonctions, déclencheurs, droits) sous forme d'un script SQL rejouable.
-- Usage : Supabase > SQL Editor > coller cette requête > Run, puis copier la colonne « ddl »
-- dans supabase/schema.sql. Aucune donnée n'est exportée, seulement la structure.
with
tables as (
  select c.oid, c.relname, c.relrowsecurity
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
),
colonnes as (
  select t.relname, string_agg(
    format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
      case when a.attidentity = 'a' then ' generated always as identity'
           when a.attidentity = 'd' then ' generated by default as identity'
           when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
      case when a.attnotnull then ' not null' else '' end),
    E',\n' order by a.attnum) as cols
  from tables t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  group by t.relname
),
blocs as (
  -- 1. Tables (colonnes seulement ; les contraintes viennent ensuite, pour gérer les clés étrangères)
  select 1 as ordre, t.relname as nom,
    format(E'create table if not exists public.%I (\n%s\n);', t.relname, c.cols) as ddl
  from tables t join colonnes c using (relname)
  union all
  -- 2. Contraintes (clés primaires et uniques avant les clés étrangères)
  select case when co.contype = 'f' then 3 else 2 end, t.relname || '.' || co.conname,
    format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from tables t join pg_constraint co on co.conrelid = t.oid
  union all
  -- 3. Index qui ne viennent pas d'une contrainte
  select 4, i.relname, pg_get_indexdef(i.oid) || ';'
  from tables t join pg_index x on x.indrelid = t.oid join pg_class i on i.oid = x.indexrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.oid)
  union all
  -- 4. Sécurité au niveau des lignes
  select 5, t.relname, format('alter table public.%I enable row level security;', t.relname)
  from tables t where t.relrowsecurity
  union all
  -- 5. Fonctions
  select 6, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  -- 6. Politiques RLS (après les fonctions, qu'elles peuvent appeler)
  select 7, po.tablename || '.' || po.policyname,
    format('create policy %I on public.%I as %s for %s to %s%s%s;', po.policyname, po.tablename,
      po.permissive, po.cmd, array_to_string(po.roles, ', '),
      case when po.qual is not null then ' using (' || po.qual || ')' else '' end,
      case when po.with_check is not null then ' with check (' || po.with_check || ')' else '' end)
  from pg_policies po where po.schemaname = 'public'
  union all
  -- 7. Déclencheurs
  select 8, tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from tables t join pg_trigger tg on tg.tgrelid = t.oid where not tg.tgisinternal
  union all
  -- 8. Droits d'exécution des fonctions (on retire tout, puis on redonne exactement ce qui existe)
  select 9, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    format('revoke all on function public.%I(%s) from public, anon, authenticated;', p.proname,
      pg_get_function_identity_arguments(p.oid))
    || coalesce((select string_agg(format(E'\ngrant execute on function public.%I(%s) to %I;', p.proname,
         pg_get_function_identity_arguments(p.oid), r.rolname), '' order by r.rolname)
       from pg_roles r where r.rolname in ('anon', 'authenticated')
         and has_function_privilege(r.oid, p.oid, 'execute')), '')
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  -- 9. Droits sur les tables pour les rôles de l'API
  select 10, t.relname || '.' || r.rolname,
    format('grant %s on public.%I to %I;', string_agg(pr.privilege_type, ', ' order by pr.privilege_type), t.relname, r.rolname)
  from tables t cross join pg_roles r
  cross join lateral (select unnest(array['SELECT','INSERT','UPDATE','DELETE']) as privilege_type) pr
  where r.rolname in ('anon', 'authenticated') and has_table_privilege(r.oid, t.oid, pr.privilege_type)
  group by t.relname, r.rolname
)
select string_agg(ddl, E'\n\n' order by ordre, nom) as ddl from blocs;
